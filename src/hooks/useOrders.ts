import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { supabase } from '@/integrations/supabase/client';
import { Tables, TablesInsert, TablesUpdate, Json } from '@/integrations/supabase/types';
import { toast } from 'sonner';
import { useEffect } from 'react';
import { useAuth } from '@/contexts/AuthContext';

export type OrderRow = Tables<'orders'>;
export type OrderInsert = TablesInsert<'orders'>;
export type OrderUpdate = TablesUpdate<'orders'>;
export type OrderItemRow = Tables<'order_items'>;
export type OrderItemInsert = TablesInsert<'order_items'>;

export type OrderStatus = 'pending' | 'preparing' | 'ready' | 'served' | 'completed';

export interface OrderWithItems extends OrderRow {
  order_items: (OrderItemRow & {
    menu_items: Tables<'menu_items'> | null;
  })[];
}

export function useOrders() {
  const queryClient = useQueryClient();
  
  const query = useQuery({
    queryKey: ['orders'],
    queryFn: async () => {
      const { data, error } = await supabase
        .from('orders')
        .select(`
          *,
          order_items (
            *,
            menu_items (*)
          )
        `)
        .order('created_at', { ascending: false });
      
      if (error) throw error;
      return data as OrderWithItems[];
    },
  });

  // Subscribe to realtime updates
  useEffect(() => {
    const channel = supabase
      .channel('orders-changes')
      .on(
        'postgres_changes',
        { event: '*', schema: 'public', table: 'orders' },
        () => {
          queryClient.invalidateQueries({ queryKey: ['orders'] });
        }
      )
      .on(
        'postgres_changes',
        { event: '*', schema: 'public', table: 'order_items' },
        () => {
          queryClient.invalidateQueries({ queryKey: ['orders'] });
        }
      )
      .subscribe();

    return () => {
      supabase.removeChannel(channel);
    };
  }, [queryClient]);

  return query;
}

export function useCreateOrder() {
  const queryClient = useQueryClient();
  const { user } = useAuth();
  
  return useMutation({
    mutationFn: async ({
      order,
      items,
    }: {
      order: Omit<OrderInsert, 'order_number' | 'created_by'>;
      items: Omit<OrderItemInsert, 'order_id'>[];
    }) => {
      // Create order - order_number is auto-generated by trigger
      const { data: insertData, error: orderError } = await supabase
        .from('orders')
        .insert({
          ...order,
          order_number: 'TEMP', // Will be overwritten by trigger
          created_by: user?.id,
        })
        .select('id')
        .single();
      
      if (orderError) throw orderError;
      
      // Re-fetch to get the trigger-generated order_number
      const { data: orderData, error: fetchError } = await supabase
        .from('orders')
        .select()
        .eq('id', insertData.id)
        .single();
      
      if (fetchError) throw fetchError;
      
      // Create order items
      const orderItems = items.map(item => ({
        ...item,
        order_id: orderData.id,
      }));
      
      const { error: itemsError } = await supabase
        .from('order_items')
        .insert(orderItems);
      
      if (itemsError) throw itemsError;
      
      return orderData;
    },
    onSuccess: (data) => {
      queryClient.invalidateQueries({ queryKey: ['orders'] });
      toast.success(`Order ${data.order_number} created successfully!`);
    },
    onError: (error) => {
      toast.error('Failed to create order: ' + error.message);
    },
  });
}

// For customer self-ordering (no auth required)
export function useCreateCustomerOrder() {
  const queryClient = useQueryClient();
  
  return useMutation({
    mutationFn: async ({
      order,
      items,
    }: {
      order: Omit<OrderInsert, 'order_number' | 'created_by'>;
      items: Omit<OrderItemInsert, 'order_id'>[];
    }) => {
      // Generate a unique order number using timestamp + random suffix
      const now = new Date();
      const dateStr = now.toISOString().slice(2, 10).replace(/-/g, '');
      const randomSuffix = Math.random().toString(36).substring(2, 6).toUpperCase();
      const clientOrderNumber = `ORD-${dateStr}-${randomSuffix}`;
      
      // Pure INSERT without .select() to avoid RLS read restrictions
      // The database trigger will generate a proper order_number
      const { data: insertData, error: orderError } = await supabase
        .from('orders')
        .insert({
          ...order,
          order_number: clientOrderNumber,
          created_by: null, // Explicitly null for public orders
        })
        .select('id, order_number');

      if (orderError) throw orderError;

      // If RLS blocks the select, insertData will be empty but order was still created
      const orderId = insertData?.[0]?.id;
      const orderNumber = insertData?.[0]?.order_number || clientOrderNumber;

      if (!orderId) {
        // Order was created but we can't get the ID due to RLS
        // For customer flow, this is acceptable - they get their order number
        return {
          id: '',
          order_number: clientOrderNumber,
          ...order,
          created_by: null,
          created_at: new Date().toISOString(),
          updated_at: new Date().toISOString(),
        } as OrderRow;
      }

      // If we have the ID, create order items
      if (items.length > 0) {
        const orderItems = items.map(item => ({
          ...item,
          order_id: orderId,
        }));

        const { error: itemsError } = await supabase
          .from('order_items')
          .insert(orderItems);

        if (itemsError) {
          console.error('Failed to create order items:', itemsError);
          // Don't throw - order was created, items failed
        }
      }

      return {
        id: orderId,
        order_number: orderNumber,
        ...order,
        created_by: null,
        created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      } as OrderRow;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['orders'] });
    },
    onError: (error) => {
      throw error;
    },
  });
}

export function useCreateOrderItem() {
  return useMutation({
    mutationFn: async (item: OrderItemInsert) => {
      // NOTE: Public customers can INSERT but cannot SELECT order_items (RLS)
      const { error } = await supabase
        .from('order_items')
        .insert(item);

      if (error) throw error;
      return item;
    },
  });
}

export function useUpdateOrderStatus() {
  const queryClient = useQueryClient();
  
  return useMutation({
    mutationFn: async ({ id, status }: { id: string; status: OrderStatus }) => {
      const { data, error } = await supabase
        .from('orders')
        .update({ status })
        .eq('id', id)
        .select()
        .single();
      
      if (error) throw error;
      return data;
    },
    onSuccess: (data) => {
      queryClient.invalidateQueries({ queryKey: ['orders'] });
      toast.success(`Order ${data.order_number} marked as ${data.status}`);
    },
    onError: (error) => {
      toast.error('Failed to update order: ' + error.message);
    },
  });
}

